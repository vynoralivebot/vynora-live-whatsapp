-- Vynora Live WhatsApp: initial users table
-- Run this in Supabase SQL Editor.
-- RLS is enabled. No public/anon access policies are created.
-- The backend accesses this table using SUPABASE_SECRET_KEY only.

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    phone_number text not null unique,
    display_name text,
    role text not null default 'user'
        check (role in ('user', 'host', 'admin')),
    coins integer not null default 0 check (coins >= 0),
    last_seen_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.users enable row level security;

create index if not exists idx_users_role on public.users(role);
create index if not exists idx_users_last_seen_at on public.users(last_seen_at);
